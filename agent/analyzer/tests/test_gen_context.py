def test_parser_directives_hoisted_above_marker(tmp_path):
    repo = tmp_path / "app"
    _require(repo)
    _write(os.path.join(repo, "Dockerfile.app"),
           "# syntax=docker/dockerfile:1\nFROM python:3.9-slim\n"
           "RUN --mount=type=cache target=/root/.cache pip install -r requirements.txt\n")
    _write(os.path.join(repo, "main.py"), _SELF_SERVING_APP)
    gen_context.generate(str(repo), str(repo), force=True)
    dockerfile = open(_pf(repo), encoding="utf-8").read()
    # the directive must precede our marker to stay recognized by Docker
    assert dockerfile.index("# syntax=docker/dockerfile:1") < \
        dockerfile.index("# Generated by PatchProof")
    assert "--mount=type=cache" in dockerfile


