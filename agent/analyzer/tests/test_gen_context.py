"""Unit tests for gen_context — version-matched minimal synthesis contract.

The working build definition is ALWAYS `Dockerfile.patchproof`: a minimal
official base matched to the repo's runtime version + our own uniform
install lines. Repo Dockerfile* files are read for version hints only and
are never overwritten or executed.
"""

import json
import os

import pytest

from agent.analyzer import gen_context

_SELF_SERVING_APP = (
    "import uvicorn\n"
    "app = 'placeholder'\n"
    "if __name__ == '__main__':\n"
    "    uvicorn.run(app)\n")
_NODE_LISTENER = ("const http = require('http');\n"
                  "http.createServer(() => {}).listen(3000, '127.0.0.1');\n")


def _write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)


def _require(repo, body="pyyaml==3.13\n"):
    _write(os.path.join(repo, "requirements.txt"), body)


def _pf(repo):
    return os.path.join(str(repo), "Dockerfile.patchproof")


# ------------------------------------------------------------- synthesis

def test_synthesizes_version_matched_slim_base(tmp_path):
    repo = tmp_path / "app"
    _require(repo)
    _write(os.path.join(repo, "main.py"), _SELF_SERVING_APP)
    result = gen_context.generate(str(repo), str(repo))
    assert result["source"] == "synthesized"
    assert result["base_image"] == "python:3.11-slim"  # no hints → default
    assert result["runtime_version"] == "3.11"
    assert result["dockerfile_name"] == "Dockerfile.patchproof"
    dockerfile = open(_pf(repo), encoding="utf-8").read()
    assert dockerfile.startswith("# Generated by PatchProof")
    assert "FROM python:3.11-slim" in dockerfile
    assert 'CMD ["python", "main.py"]' in dockerfile
    # the repo's own Dockerfile* files are never created or written
    assert not os.path.exists(os.path.join(str(repo), "Dockerfile"))


