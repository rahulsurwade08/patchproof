# ------------------------------------------------------- declared reuse

def test_reuses_declared_dockerfile_verbatim(tmp_path):
    repo = tmp_path / "app"
    _require(repo, body="old-pin==1.0\n")
    _write(os.path.join(repo, "Dockerfile.app"),
           "FROM python:alpine3.8\nRUN apk add --no-cache gcc musl-dev\n")
    _write(os.path.join(repo, "main.py"), _SELF_SERVING_APP)
    result = gen_context.generate(str(repo), str(repo))
    assert result["source"] == "repo-dockerfile"
    assert result["base_image"] == "python:alpine3.8"
    assert result["generated"] is True  # the .patchproof build file is generated
    # verbatim: the repo's own RUN steps (build tooling) survive
    dockerfile = open(_pf(repo), encoding="utf-8").read()
    assert "apk add --no-cache gcc musl-dev" in dockerfile
    # the repo's own Dockerfile* files are untouched
    assert open(os.path.join(str(repo), "Dockerfile.app")).read() == \
        "FROM python:alpine3.8\nRUN apk add --no-cache gcc musl-dev\n"
    assert not os.path.exists(os.path.join(str(repo), "Dockerfile"))


def test_workdir_honored_in_start_command(tmp_path):
    repo = tmp_path / "app"
    _require(repo)
    _write(os.path.join(repo, "Dockerfile.app"), (
        "FROM python:3.9-slim\nWORKDIR /app\n"
        "COPY . /app\nRUN pip install -r requirements.txt\n"))
    _write(os.path.join(repo, "main.py"), _SELF_SERVING_APP)
    result = gen_context.generate(str(repo), str(repo))
    assert result["workdir"] == "/app"
    dockerfile = open(_pf(repo), encoding="utf-8").read()
    cmd_line = next(l for l in dockerfile.splitlines() if l.startswith("CMD "))
    assert json.loads(cmd_line[4:]) == ["sh", "-c",
                                        "cd /app && python main.py"]


