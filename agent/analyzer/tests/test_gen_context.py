def test_all_interface_binds_rejected(tmp_path):
    for lang, entry, body in (
            ("node", "server.js", "http.createServer(()=>{}).listen(3000);\n"),
            ("py", "main.py",
             "import tornado.ioloop\nimport tornado.web\n"
             "app = tornado.web.Application([])\napp.listen(8888)\n"
             "tornado.ioloop.IOLoop.current().start()\n")):
        repo = tmp_path / f"app-{lang}"
        if lang == "node":
            _write(os.path.join(repo, "package.json"), json.dumps(
                {"dependencies": {}}))
            _write(os.path.join(repo, entry), body)
        else:
            _require(repo)
            _write(os.path.join(repo, entry), body)
        with pytest.raises(ValueError):
            gen_context.generate(str(repo), str(repo))


