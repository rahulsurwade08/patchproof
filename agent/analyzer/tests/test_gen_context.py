def test_installs_uvicorn_launcher_before_repo_deps(tmp_path):
    repo = tmp_path / "app"
    _require(repo, body="fastapi==0.115.0\nuvicorn==0.29.0\n")
    _write(os.path.join(repo, "main.py"),
           "from fastapi import FastAPI\napp = FastAPI()\n")
    result = gen_context.generate(str(repo), str(repo))
    assert result["start_command"][0] == "uvicorn"
    dockerfile = open(_pf(repo), encoding="utf-8").read()
    # ordering: build tools -> uvicorn launcher -> repo deps, so a repo
    # pin (uvicorn==0.29.0) re-asserts itself during the deps install
    apt = dockerfile.index("apt-get install")
    uv = dockerfile.index("uvicorn>=0.30")
    deps_install = dockerfile.index("pip install --no-cache-dir -r requirements.txt")
    assert apt < uv < deps_install


